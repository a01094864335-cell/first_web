import assert from 'node:assert/strict';
import {renderMapScene,sceneDepth} from '../public/assets/cafe-map/map-scene.js';
const layout={objects:[{id:'floor',asset:'floor.png',x:0,y:0,width:1,height:1,depth:0},{id:'plant',asset:'plant.png',x:.8,y:.1,width:.1,height:.2,depth:.3,interaction:{action:'plant',label:'화분 살펴보기',anchor:{x:.75,y:.3},badge:{x:.85,y:.08}}}]};
const html=renderMapScene(layout);
assert(html.includes('data-map-object="plant"'));
assert(html.includes('data-map-target="plant"'));
assert(html.includes('left:85%;top:8%'));
assert(html.includes('z-index:400'));
assert(sceneDepth(.29)<sceneDepth(.3));
assert(sceneDepth(.31)>sceneDepth(.3));
assert(!html.includes('background.webp'));
assert.throws(()=>renderMapScene({objects:[{...layout.objects[0],asset:'../../secret.png'}]}));
assert(renderMapScene(null).includes('role="status"'));
console.log('Map scene: separate asset nodes, depth, hotspot and path checks passed (not visual QA).');
const {readFile,stat}=await import('node:fs/promises');
const actual=JSON.parse(await readFile(new URL('../public/assets/cafe-map/layout.json',import.meta.url)));
assert.equal(actual.objects.length,64);
for(const object of actual.objects) assert((await stat(new URL('../public/assets/cafe-map/'+object.asset,import.meta.url))).size>0);
const tables=actual.objects.filter(o=>o.asset.includes('round-table'));
assert.equal(tables.length,6);assert.equal(new Set(tables.map(t=>t.width+':'+t.height)).size,1);
console.log('Final map: 64 independent objects, all asset files present, six equal table dimensions.');
